/// Glyph bitmaps indexed by ASCII code; each row holds 5 bits (bit 4 = leftmost).
pub struct Font {
    rows: [[u8; 7]; 128],
    present: [bool; 128],
}

impl Font {
    pub fn build() -> Self {
        let mut rows = [[0u8; 7]; 128];
        let mut present = [false; 128];
        for (ch, art) in GLYPHS {
            let i = *ch as usize;
            present[i] = true;
            for (y, line) in art.iter().enumerate() {
                for (x, c) in line.bytes().enumerate() {
                    if c == b'#' {
                        rows[i][y] |= 1 << (4 - x);
                    }
                }
            }
        }
        present[b' ' as usize] = true; // blank
        Self { rows, present }
    }

    pub fn has(&self, c: u8) -> bool {
        (c as usize) < 128 && self.present[c as usize]
    }

    /// Is pixel (x, y) of a `cell`-sized square showing glyph `c` lit?
    /// The 5x7 bitmap is nearest-neighbour scaled into an 8x8 box (x offset 1).
    #[inline]
    pub fn pixel(&self, c: u8, x: usize, y: usize, cell: usize) -> bool {
        let vx = x * 8 / cell;
        let vy = y * 8 / cell;
        if !(1..=5).contains(&vx) || vy >= 7 || (c as usize) >= 128 {
            return false;
        }
        self.rows[c as usize][vy] >> (5 - vx) & 1 == 1
    }

    /// Cells of `text` as a bitmap pattern (6 columns per char, 7 rows).
    pub fn text_cells(&self, text: &str) -> (usize, usize, Vec<(usize, usize)>) {
        let mut cells = Vec::new();
        let mut x0: usize = 0;
        for c in text.bytes() {
            if (c as usize) < 128 {
                for y in 0..7 {
                    for x in 0..5 {
                        if self.rows[c as usize][y] >> (4 - x) & 1 == 1 {
                            cells.push((x0 + x, y));
                        }
                    }
                }
            }
            x0 += 6;
        }
        (x0.saturating_sub(1), 7, cells)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyph_rows_are_5_wide() {
        for (c, art) in GLYPHS {
            for line in art {
                assert_eq!(line.len(), 5, "glyph {c:?}");
            }
        }
    }

    #[test]
    fn needed_chars_exist() {
        let f = Font::build();
        for c in
            "0123456789ABCDEF gen pop hz highlife daynight seeds brain life b3/s23 rotate".bytes()
        {
            assert!(f.has(c), "missing {:?}", c as char);
        }
    }
}
